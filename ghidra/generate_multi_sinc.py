#!/usr/bin/env python3
"""Write MIL1750A_multi.sinc: explicit expansions of LM, STM, PSHM and POPM.

The register lists are known at decode time. Spelling each one out, rather than
looping over register space, lets the decompiler see which registers are involved.

    ghidra/generate_multi_sinc.py > ghidra/MIL1750A/data/languages/MIL1750A_multi.sinc
"""


def pop_order(ra, rb):
    return list(range(ra, rb + 1)) if ra <= rb else list(range(ra, 16)) + list(range(0, rb + 1))


def push_order(ra, rb):
    """Pushed last goes lowest in memory, so RA ends up on top of the stack."""
    return list(reversed(pop_order(ra, rb)))


def main():
    print("# Generated by ghidra/generate_multi_sinc.py. Do not edit.\n")
    for n in range(16):
        loads = " ".join(f"R{i} = *[ram]:2 (ea + {i});" for i in range(n + 1))
        print(f':LM "0x{n:X}",ea is (op8=0x89 & hi4={n}) ... & ea {{ {loads} }}')
    print()
    for n in range(16):
        stores = " ".join(f"*[ram]:2 (ea + {i}) = R{i};" for i in range(n + 1))
        print(f':STM "0x{n:X}",ea is (op8=0x99 & hi4={n}) ... & ea {{ {stores} }}')
    print()
    for ra in range(16):
        for rb in range(16):
            # R15 is the stack pointer, so popping it only skips the word.
            steps = [(f"R{reg} = *[ram]:2 R15; " if reg != 15 else "") + "R15 = R15 + 1;"
                     for reg in pop_order(ra, rb)]
            print(f"popm_list: is ra={ra} & rb={rb} {{ {' '.join(steps)} }}")
    print()
    for ra in range(16):
        for rb in range(16):
            steps = [f"R15 = R15 - 1; *[ram]:2 R15 = R{reg};" for reg in push_order(ra, rb)]
            print(f"pshm_list: is ra={ra} & rb={rb} {{ {' '.join(steps)} }}")


if __name__ == "__main__":
    main()
